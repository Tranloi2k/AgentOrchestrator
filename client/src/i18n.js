export function translate(locale, key, vars = {}) {
  let str = translations[locale]?.[key] ?? translations.vi[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replaceAll(`{${k}}`, String(v));
  }
  return str;
}
